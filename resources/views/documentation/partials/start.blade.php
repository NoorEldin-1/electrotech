    </p>

    <p>
        المنصة دي بتمسك السلسلة دي كلها في مكان واحد. بدل ما كل قسم يكتب في دفتر لوحده
        ويحصل لخبطة، كل قسم بيشتغل على شاشته — والنظام بيوصّل المعلومة للقسم اللي بعده
        <strong>لوحده</strong>. لما المخزن يصرف خامة، تكلفتها بتتحمّل على المشروع فورًا؛ ولما
        تتسلّم بضاعة للعميل، حساب العميل بيتحرّك فورًا.
    </p>

    <div class="doc-grid-2">
