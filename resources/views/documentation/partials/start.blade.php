        <strong>إلكتروتك عروة</strong> شركة بتصنّع منتجات كهربائية (قضبان توزيع الكهرباء / Busway).
        الشغل بيمشي كده: عميل بيطلب سعر ← بنعمله عرض ← لو وافق بنعمل تصميم وقايمة مواد ←
