        <br><br>
        التقسيم ده بيتعمل <strong>لوحده</strong> من كشوف حساب العملاء والموردين، وتحت الشاشة
        فيه قسم مطوي بيوريك <strong>كل طرف باسمه ورصيده</strong> في أي ناحية وقع.
    </x-doc.callout>

    <x-doc.callout type="warn" title="سطر «فرق مطابقة» — لو ظهر يبقى فيه حاجة تستاهل نظرة">
        لو مجموع كشوف حساب العملاء (أو الموردين) <strong>مش مساوي</strong> رصيد حساب المراقبة
        في الدفاتر، النظام <strong>ما بيخبّيش</strong> الفرق — بيطلّعه في سطر لوحده بشارة صفرا.
        القائمة بتفضل متوازنة، وأنت بتشوف الفرق وتراجعه. أشهر سبب: قيد يدوي على حساب المراقبة
        من غير ما يتسجّل على طرف معيّن.
    </x-doc.callout>

    <x-doc.callout type="info" title="حاشية آخر القائمة (شيكات وخطابات الضمان)">
        فيه حسابات <strong>ما بتدخلش المعادلات</strong> عشان مش ملكك ولا عليك فعليًا — زي شيكات
        الضمان. دي بتظهر في قسم لوحده آخر الصفحة بصيغة «يوجد شيكات ضمان بمبلغ …» — للعلم بس.
    </x-doc.callout>

    <x-doc.callout type="tip" title="الحساب الرئيسي بيبلع اللي تحته">
        لو عملت حسابات فرعية تحت حساب رئيسي، القائمة بتعرض <strong>الرئيسي بس</strong> برصيده
        ورصيد كل اللي تحته مجموعين فيه. كده القائمة بتفضل قصيرة ومقروءة مهما كبرت الشجرة.
    </x-doc.callout>
</x-doc.section>


