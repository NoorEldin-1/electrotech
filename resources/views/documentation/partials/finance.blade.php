    <x-doc.callout type="info" title="الأصول الثابتة بتلاتة أعمدة">
        كل أصل بيظهر بـ<strong>التكلفة</strong> و<strong>مجمع الإهلاك</strong>
        و<strong>الصافي</strong> — بالظبط زي ورق المحاسب. عشان النظام يعرف أي مجمع إهلاك يخصم
