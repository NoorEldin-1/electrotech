        <strong>العميل اللي ليك عنده فلوس</strong> ← بيظهر في <strong>الأصول</strong>.
        <strong>العميل اللي دفع لك مقدّم</strong> ← بيظهر في <strong>الالتزامات المتداولة</strong>
