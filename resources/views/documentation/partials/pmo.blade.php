        <ol>
            <li>مكتب المشروعات بيعمل أمر تصنيع «WO-2026-014» لـ<strong>٥ لوحات 630A</strong> على مشروع «برج النيل». الحالة: <strong>مسودة</strong>.</li>
            <li>الخامات بتتملّى لوحدها من الوصفة القياسية: ٤٢م نحاس، ٦١ عازل، ١٦ لوح صاج.</li>
            <li>المهندس شايف إن ده المشروع محتاج نحاس زيادة، فبيعدّل الكمية لـ<strong>٤٥ متر</strong> يدوي. (الوصفة القياسية زي ما هي.)</li>
