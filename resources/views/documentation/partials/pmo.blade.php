        <ol>
            <li>مكتب المشروعات بيعمل أمر تصنيع «WO-2026-014» على مشروع «برج النيل»، وبيضيف <strong>منتجين</strong>: ٥ لوحات 630A و٢ لوحة 250A. الكمية المخططة للأمر بتطلع <strong>٧</strong> لوحدها. الحالة: <strong>مسودة</strong>.</li>
            <li>الخامات بتتملّى لوحدها من الوصفتين القياسيتين مع بعض: ٤٢م نحاس (من المنتجين)، ٦١ عازل، ١٦ لوح صاج.</li>
            <li>المهندس شايف إن ده المشروع محتاج نحاس زيادة، فبيعدّل الكمية لـ<strong>٤٥ متر</strong> يدوي. (الوصفة القياسية زي ما هي.)</li>
            <li>مدير مكتب المشروعات بيضغط <strong>«اعتماد الأمر»</strong> ← الحالة <strong>معلّق</strong>.</li>
            <li>المصنع بيضغط <strong>«بدء»</strong> ← الحالة <strong>قيد التنفيذ</strong>، والساعة بتبدأ.</li>
            <li>بيضغط <strong>«صرف الخامات»</strong> ← إذن صرف مسودة بيروح للمخزن. المخزن بيرحّله ← <strong>الخامات بتخرج من مخزن الخامات لتحت التشغيل، و«التكلفة الفعلية» للعملية بتزيد</strong>.</li>
            <li>في نص الشغل فضل ٣ متر نحاس ← <strong>«ارتداد فضلات»</strong> ← المخزن يرحّل ← التكلفة تنقص بقيمة الـ ٣ متر.</li>
            <li>لوح صاج اتقطع غلط ← <strong>«إهلاك»</strong> ← بيتشال من المخزون وقيمته تروح لحساب الهالك.</li>
            <li>التصنيع خلص ← <strong>«إرسال لضمان الجودة»</strong> ← بيكتب لكل منتج كميته: ٥ من 630A سليمة، و١ من 250A سليمة وواحدة هالك.</li>
            <li><strong>«اعتماد الجودة»</strong> ← الجودة بتوقّع على الأمر.</li>
            <li>دلوقتي بس زر <strong>«انتهاء التصنيع»</strong> بيظهر (لأن الاعتمادين خلصوا) ← إشعار لكل الأقسام + ورقة جودة مسودة اتعملت. المدة اتسجّلت: ٦ أيام.</li>
            <li>أخيرًا <strong>«إتمام»</strong> ← <strong>٥ لوحات 630A و١ لوحة 250A بيدخلوا مخزن المنتجات التامة</strong>، وبيتسجّل سطر إنتاج لكل منتج، والأمر بيتقفل.</li>
        </ol>
